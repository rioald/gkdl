#!/bin/bash
# Called by build.sh for beta/canary. No input-source installation.
set -euo pipefail
cd "$(dirname "$0")/.."
stage=$1
parent=$2
python3 - <<'PY'
import hashlib,json
from pathlib import Path
root=Path('ThirdParty/Araso')
for name,info in json.loads((root/'UPSTREAM.json').read_text())['files'].items():
    if hashlib.sha256((root/name).read_bytes()).hexdigest()!=info['sha256']:
        raise SystemExit('Araso source mismatch: '+name)
PY
app="$parent/Contents/PlugIns/하이 Beta 입력기.app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
for arch in arm64 x86_64; do
  module="$stage/araso-$arch"
  mkdir -p "$module"
  swiftc -swift-version 5 -O -parse-as-library -emit-library -static -emit-module -module-name ArasoCore \
    -target "$arch-apple-macos13.0" -module-cache-path "$stage/module-cache" \
    ThirdParty/Araso/Sources/*.swift -emit-module-path "$module/ArasoCore.swiftmodule" -o "$module/libArasoCore.a"
  swiftc -swift-version 5 -O -target "$arch-apple-macos13.0" -module-cache-path "$stage/module-cache" \
    -I "$module" -L "$module" -lArasoCore ArasoBeta/*.swift \
    -framework AppKit -framework Carbon -framework InputMethodKit -o "$module/HiBetaInput"
done
lipo -create "$stage/araso-arm64/HiBetaInput" "$stage/araso-x86_64/HiBetaInput" -output "$app/Contents/MacOS/HiBetaInput"
python3 - "$app" "$parent" <<'PY'
import plistlib,sys
from pathlib import Path
app,parent=map(Path,sys.argv[1:])
version=plistlib.loads((parent/'Contents/Info.plist').read_bytes())
identity='com.zzune.gkdl.beta.inputmethod'
info=dict(CFBundleDevelopmentRegion='ko',CFBundleDisplayName='하이 Beta',CFBundleName='하이 Beta',
          CFBundleExecutable='HiBetaInput',CFBundleIdentifier=identity,CFBundlePackageType='APPL',
          CFBundleShortVersionString=version['CFBundleShortVersionString'],CFBundleVersion=version['CFBundleVersion'],
          InputMethodConnectionName=identity+'_Connection',InputMethodServerControllerClass='HiBetaInputController',
          LSBackgroundOnly=True,LSUIElement=True,LSMinimumSystemVersion='13.0',NSPrincipalClass='NSApplication',
          TISInputSourceID=identity,TISIntendedLanguage='ko',TISIconIsTemplate=True,
          tsInputMethodCharacterRepertoireKey=['Latn','Hang'],tsInputMethodIconFileKey='InputIcon.tiff')
(app/'Contents/Info.plist').write_bytes(plistlib.dumps(info))
PY
cp ThirdParty/Araso/Data/*.txt "$app/Contents/Resources/"
cp "$parent/Contents/Resources/AppIcon.icns" "$app/Contents/Resources/"
# A template menu glyph; use the existing Hi artwork generated by the parent build.
sips -s format tiff "$stage/AppIcon.iconset/icon_32x32.png" --out "$app/Contents/Resources/InputIcon.tiff" >/dev/null
cat ThirdParty/Araso/NOTICE.txt ThirdParty/Araso/LICENSE ThirdParty/Araso/Notices/* > "$app/Contents/Resources/ThirdPartyNotices.txt"
cp "$app/Contents/Resources/ThirdPartyNotices.txt" "$parent/Contents/Resources/ThirdPartyNotices.txt"
test_app="$stage/araso-tests.app"
ditto "$app" "$test_app"
arch=$(uname -m)
swiftc -D TESTS -swift-version 5 -O -target "$arch-apple-macos13.0" -module-cache-path "$stage/module-cache" \
  -I "$stage/araso-$arch" -L "$stage/araso-$arch" -lArasoCore ArasoBeta/*.swift \
  -framework AppKit -framework Carbon -framework InputMethodKit -o "$test_app/Contents/MacOS/HiBetaInput"
"$test_app/Contents/MacOS/HiBetaInput" --self-test
